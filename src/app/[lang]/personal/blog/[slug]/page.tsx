import { ArrowLeftIcon } from "@phosphor-icons/react/dist/ssr/ArrowLeft";
import type { Metadata } from "next";
import Link from "next/link";
import { notFound, permanentRedirect } from "next/navigation";

import { AuthorCard } from "@/components/blog/author-card";
import { PostHeader } from "@/components/blog/post-header";
import { PostPager } from "@/components/blog/post-pager";
import { RssLink } from "@/components/blog/rss-link";
import { TableOfContents } from "@/components/blog/table-of-contents";
import { Reveal } from "@/components/motion/reveal";
import { LocaleAlternates } from "@/components/providers/alternate-links";
import { JsonLd } from "@/components/seo/json-ld";
import { Container } from "@/components/ui/container";
import { Prose } from "@/components/ui/prose";
import { TagList } from "@/components/ui/tag";
import { getDictionary, isLocale, otherLocales } from "@/i18n";
import { formatDate, toIsoDate } from "@/i18n/format";
import {
  findTranslatedPostUrl,
  getAdjacentPosts,
  getAllPostParams,
  getPost,
  getPostAlternates,
  getPostTranslations,
} from "@/lib/blog";
import { routes } from "@/lib/routes";
import {
  blogPostingJsonLd,
  breadcrumbJsonLd,
  buildMetadata,
  personJsonLd,
} from "@/lib/seo";
import { absoluteUrl } from "@/lib/utils";

type PageProps = { params: Promise<{ lang: string; slug: string }> };

/**
 * Every published post is prerendered. Unknown slugs still render on demand,
 * only so a slug from the other locale can redirect to its translation
 * (see below); anything else is a 404.
 */
export const dynamicParams = true;

export function generateStaticParams() {
  return getAllPostParams();
}

export async function generateMetadata({
  params,
}: PageProps): Promise<Metadata> {
  const { lang, slug } = await params;
  if (!isLocale(lang)) return {};
  const post = await getPost(lang, slug);
  if (!post) return {};
  return buildMetadata({
    lang,
    title: post.title,
    description: post.description,
    alternates: getPostAlternates(post),
    type: "article",
    keywords: post.tags,
    article: {
      publishedTime: post.date,
      modifiedTime: post.updated ?? post.date,
      tags: post.tags,
    },
  });
}

export default async function PostPage({ params }: PageProps) {
  const { lang, slug } = await params;
  if (!isLocale(lang)) notFound();
  const post = await getPost(lang, slug);
  if (!post) {
    // e.g. /pt-br/personal/blog/hello-world -> /pt-br/personal/blog/ola-mundo
    const translated = findTranslatedPostUrl(lang, slug);
    if (translated) permanentRedirect(translated);
    notFound();
  }

  const dict = getDictionary(lang);
  const alternates = getPostAlternates(post);
  const translations = getPostTranslations(post);
  const translation = otherLocales(lang)
    .map((other) => translations[other])
    .find(Boolean);
  const { newer, older } = getAdjacentPosts(post);
  // "Updated on {date}": render the date as a <time> inside the sentence.
  const [updatedBefore, updatedAfter = ""] =
    dict.blog.updatedOn.split("{date}");
  const updated =
    post.updated && post.updated !== post.date ? post.updated : undefined;

  return (
    <Container as="article" className="pt-8 sm:pt-14">
      <LocaleAlternates links={alternates} />
      <JsonLd
        data={[
          personJsonLd(lang),
          blogPostingJsonLd(post, {
            // Generated by the segment's opengraph-image route.
            image: absoluteUrl(`${post.url}/opengraph-image`),
            translations: alternates,
          }),
          breadcrumbJsonLd([
            { name: dict.meta.siteName, path: routes.work(lang) },
            { name: dict.nav.personal, path: routes.personal(lang) },
            { name: dict.blog.title, path: routes.blog(lang) },
            { name: post.title, path: post.url },
          ]),
        ]}
      />

      <PostHeader post={post} translation={translation} />

      <TableOfContents
        headings={post.headings}
        label={dict.blog.onThisPage}
        className="mt-10"
        enter={3}
      />

      <Prose html={post.html} className="mt-12 [&>p:first-child]:text-lead" />

      <footer>
        {post.tags.length > 0 || updated ? (
          <Reveal
            stagger
            className="mt-14 flex flex-wrap items-center justify-between gap-4"
          >
            {post.tags.length > 0 ? (
              <TagList items={post.tags} label={dict.blog.tags} />
            ) : null}
            {updated ? (
              <p className="text-small text-muted-foreground">
                {updatedBefore}
                <time dateTime={toIsoDate(updated)}>
                  {formatDate(updated, lang)}
                </time>
                {updatedAfter}
              </p>
            ) : null}
          </Reveal>
        ) : null}

        <Reveal className="mt-24 sm:mt-28">
          <AuthorCard lang={lang} />
        </Reveal>

        {newer || older ? (
          <Reveal className="mt-20">
            <PostPager lang={lang} newer={newer} older={older} />
          </Reveal>
        ) : null}

        <Reveal
          stagger
          className="mt-12 flex flex-wrap items-center justify-between gap-4"
        >
          <Link
            href={routes.blog(lang)}
            className="group inline-flex items-center gap-2 font-medium"
          >
            <ArrowLeftIcon
              aria-hidden="true"
              className="size-4 transition-transform duration-150 ease-out group-hover:-translate-x-0.5"
            />
            <span className="link-underline">{dict.blog.backToBlog}</span>
          </Link>
          <RssLink lang={lang} label={dict.blog.subscribe} />
        </Reveal>
      </footer>
    </Container>
  );
}
